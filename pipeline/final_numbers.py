"""Write numbers.tex: one LaTeX macro per number used in the text.

Use in the text as \\N{key}. Keys are listed in numbers_keys.txt. Each value is stored with one decimal
(or two for correlations); the suffix _i gives the integer-rounded value.
"""
import re

import numpy as np
import pandas as pd

SHORT = {"Rrs_442.5": "r442", "Rrs_490": "r490", "Rrs_560": "r560", "Rrs_665": "r665", "chlor_a": "chl"}


def _fmt(stat, x):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--", "--"
    sign = stat in ("beta", "beta_lo", "beta_hi", "closer", "mean_d_beta", "lo", "hi", "med_beta")
    if stat in ("r", "r_lo", "r_hi", "rho", "slope", "slope_lo", "slope_hi", "median_r"):
        return f"{x:.2f}".replace("-", r"\ensuremath{-}"), f"{x:.2f}".replace("-", r"\ensuremath{-}")
    if stat in ("closer_median", "closer_lo", "closer_hi"):
        return f"{x:+.3f}".replace("-", r"\ensuremath{-}"), f"{x:+.3f}".replace("-", r"\ensuremath{-}")
    if stat in ("p", "wilcoxon_p"):
        s = "<0.001" if x < 0.001 else f"{x:.3f}"
        return s, s
    if stat in ("n", "days", "n_pairs"):
        s = f"{int(x):,}".replace(",", r"\,")
        return s, s
    one = f"{x:+.1f}" if sign else f"{x:.1f}"
    integer = f"{x:+.0f}" if sign else f"{x:.0f}"
    return one.replace("-", r"\ensuremath{-}"), integer.replace("-", r"\ensuremath{-}")


class Macros:
    def __init__(self):
        self.d = {}

    def put(self, key, value, stat="x"):
        key = re.sub(r"[^A-Za-z0-9_.]", "", key.replace(" ", "").replace("<", "lt").replace(">", "gt").replace("-", "to"))
        if isinstance(value, str):
            self.d[key] = value; self.d[key + "_i"] = value
        else:
            a, b = _fmt(stat, value)
            self.d[key] = a; self.d[key + "_i"] = b

    def frame(self, prefix, df, keycols, stats):
        for _, r in df.iterrows():
            base = prefix + "_" + "_".join(str(SHORT.get(r[c], r[c])) for c in keycols)
            for s in stats:
                if s in r.index:
                    self.put(f"{base}_{s}", float(r[s]) if pd.notna(r[s]) else np.nan, s)

    def write(self, tex, keys_txt):
        lines = [r"% generated by pipeline/final_numbers.py; do not edit",
                 r"\providecommand{\N}[1]{\csname n@\detokenize{#1}\endcsname}",
                 r"\begingroup\catcode`\_=12 \catcode`\.=12 \catcode`\<=12 \catcode`\>=12 \catcode`\-=12 \catcode`\+=12"]
        for k, v in sorted(self.d.items()):
            lines.append(r"\expandafter\gdef\csname n@" + k + r"\endcsname{" + v + "}")
        lines.append(r"\endgroup")
        open(tex, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
        open(keys_txt, "w", encoding="utf-8").write("\n".join(f"{k} = {v}" for k, v in sorted(self.d.items())))
